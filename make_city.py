#!/usr/bin/env python3
"""
make_city.py - writes city_sim.xml, a toy-scale city for the MuJoCo car simulation.

Run it once (and again whenever you change the layout):
    python make_city.py

Layout (top view, 4 m x 4 m, every road 0.40 m wide):

    +-----+---+-----+---+-----+      3 vertical roads   at x = -1.2, 0, 1.2
    |  B  | | |  B  | | |  B  |      3 horizontal roads at y = -1.2, 0, 1.2
    +-----+---+-----+---+-----+      16 buildings, one per city block
    |  B  | | |  B  | | |  B  |      The 9 road crossings are the intersections
    ...                              that run_city_sim.py uses as route nodes.

run_city_sim.py imports the constants below, so the XML and the route planner
always agree on where the roads are.
"""

import random

# =============================================================================
# Layout constants (edit these to change the city, then re-run this script)
# =============================================================================
ROAD_CENTERS = [-1.2, 0.0, 1.2]     # centre line of each road (same for x and y)
ROAD_HALF_WIDTH = 0.20              # road is 0.40 m wide: room for a 11.6 cm car
ROAD_EXTENT = max(abs(c) for c in ROAD_CENTERS) + ROAD_HALF_WIDTH   # roads end here
SIDEWALK = 0.06                     # gap between road edge and building wall
ARENA_HALF = 2.0                    # the whole world is 4 m x 4 m

MIN_HEIGHT, MAX_HEIGHT = 0.15, 0.55 # building heights (m)
BUILDING_SEED = 3                   # same seed = same skyline every time
PALETTE = [                         # building wall colours
    (0.78, 0.72, 0.62), (0.70, 0.55, 0.50), (0.62, 0.68, 0.74),
    (0.80, 0.78, 0.70), (0.55, 0.62, 0.58), (0.74, 0.64, 0.72),
]

# Obstacle bodies defined in the XML (run_city_sim.py picks how many to use per level)
MAX_BARRIERS = 4                    # "road closed" barriers: obs_1 .. obs_4
MAX_PARKED = 5                      # parked cars beside the lane: obs_5 .. obs_9

OUTPUT_PATH = "city_sim.xml"


# =============================================================================
# Geometry helpers (also imported by tests)
# =============================================================================
def _lot_intervals():
    """
    Split one axis into building lots between the roads.
    Returns (pad_lo, pad_hi, building_lo, building_hi) per lot. The pad is the whole
    lot (pavement); the building is smaller on every side that touches a road.
    """
    edges = [-ARENA_HALF]
    for c in ROAD_CENTERS:
        edges += [c - ROAD_HALF_WIDTH, c + ROAD_HALF_WIDTH]
    edges.append(ARENA_HALF)

    lots = []
    for i in range(0, len(edges), 2):
        lo, hi = edges[i], edges[i + 1]
        b_lo = lo + SIDEWALK if i > 0 else lo                    # left side touches a road
        b_hi = hi - SIDEWALK if i + 1 < len(edges) - 1 else hi   # right side touches a road
        lots.append((lo, hi, b_lo, b_hi))
    return lots


def building_footprints():
    """List of buildings: centre, half sizes, height, colour and pavement pad."""
    rng = random.Random(BUILDING_SEED)
    lots = _lot_intervals()
    buildings = []
    for j, (ylo, yhi, by_lo, by_hi) in enumerate(lots):
        for i, (xlo, xhi, bx_lo, bx_hi) in enumerate(lots):
            buildings.append({
                "name": f"bld_{j}_{i}",
                "cx": (bx_lo + bx_hi) / 2, "cy": (by_lo + by_hi) / 2,
                "hx": (bx_hi - bx_lo) / 2, "hy": (by_hi - by_lo) / 2,
                "h": rng.uniform(MIN_HEIGHT, MAX_HEIGHT),
                "color": rng.choice(PALETTE),
                "pad": (xlo, xhi, ylo, yhi),
            })
    return buildings


def _centre_dashes(road_centre, along_vertical):
    """Dash centres along one road, skipping the intersections."""
    dashes, pos = [], -ROAD_EXTENT + 0.08
    while pos < ROAD_EXTENT:
        in_junction = any(abs(pos - c) < ROAD_HALF_WIDTH + 0.02 for c in ROAD_CENTERS)
        if not in_junction:
            dashes.append(pos)
        pos += 0.16
    return dashes


# =============================================================================
# XML writer
# =============================================================================
def city_xml():
    f = lambda v: f"{v:.4f}"          # compact number formatting
    w, ext = ROAD_HALF_WIDTH, ROAD_EXTENT
    x = []                            # list of XML lines
    add = x.append

    add('<mujoco model="toy_car_city">')
    add('  <!-- Generated by make_city.py. Edit the layout there, not here. -->')
    add('  <!-- Units: metres, kg, seconds, radians. Car frame: +X forward, +Y left, +Z up. -->')
    add('  <option timestep="0.002" gravity="0 0 -9.81" integrator="implicitfast"/>')
    add('  <visual>')
    add('    <headlight ambient="0.5 0.5 0.5" diffuse="0.6 0.6 0.6" specular="0 0 0"/>')
    add('    <global offwidth="1280" offheight="720"/>')
    add('  </visual>')
    add('  <asset>')
    add('    <texture name="sky" type="skybox" builtin="gradient" rgb1="0.55 0.72 0.92" '
        'rgb2="0.15 0.25 0.45" width="512" height="512"/>')
    add('    <material name="ground_mat" rgba="0.36 0.50 0.31 1"/>')
    add('  </asset>')
    add('  <worldbody>')
    add('    <light name="sun" directional="true" pos="0 0 4" dir="-0.3 -0.4 -1" diffuse="0.75 0.75 0.75"/>')

    # ---- ground (collides) and boundary walls ----
    add(f'    <geom name="floor" type="plane" size="{ARENA_HALF} {ARENA_HALF} 0.05" material="ground_mat"/>')
    wall = ARENA_HALF + 0.01
    for name, px, py, sx, sy in (("wall_n", 0, wall, wall + 0.01, 0.01),
                                 ("wall_s", 0, -wall, wall + 0.01, 0.01),
                                 ("wall_e", wall, 0, 0.01, wall + 0.01),
                                 ("wall_w", -wall, 0, 0.01, wall + 0.01)):
        add(f'    <geom name="{name}" type="box" pos="{f(px)} {f(py)} 0.1" '
            f'size="{f(sx)} {f(sy)} 0.1" rgba="0.3 0.3 0.33 1"/>')

    # ---- cameras ----
    add('    <!-- Overhead camera: sees the whole 4 m city (default view in the viewer). -->')
    add('    <camera name="overhead_cam" pos="0 0 3.6" fovy="60"/>')

    # ---- roads (visual only: contype=0 so wheels simply roll on the floor) ----
    add('    <!-- Roads: flat dark boxes, no collision -->')
    road_rgba = "0.17 0.17 0.19 1"
    for k, c in enumerate(ROAD_CENTERS):
        add(f'    <geom name="road_v{k}" type="box" pos="{f(c)} 0 0.001" size="{f(w)} {f(ext)} 0.0005" '
            f'rgba="{road_rgba}" contype="0" conaffinity="0"/>')
        add(f'    <geom name="road_h{k}" type="box" pos="0 {f(c)} 0.001" size="{f(ext)} {f(w)} 0.0005" '
            f'rgba="{road_rgba}" contype="0" conaffinity="0"/>')

    # ---- dashed centre lines ----
    add('    <!-- Dashed centre lines (visual only) -->')
    dash_rgba = "0.95 0.82 0.20 1"
    for k, c in enumerate(ROAD_CENTERS):
        for n, p in enumerate(_centre_dashes(c, True)):
            add(f'    <geom name="dash_v{k}_{n}" type="box" pos="{f(c)} {f(p)} 0.0016" '
                f'size="0.006 0.04 0.0003" rgba="{dash_rgba}" contype="0" conaffinity="0"/>')
            add(f'    <geom name="dash_h{k}_{n}" type="box" pos="{f(p)} {f(c)} 0.0016" '
                f'size="0.04 0.006 0.0003" rgba="{dash_rgba}" contype="0" conaffinity="0"/>')

    # ---- pavement pads and buildings ----
    add('    <!-- Pavement under each block (visual) and the buildings (solid) -->')
    for b in building_footprints():
        xlo, xhi, ylo, yhi = b["pad"]
        add(f'    <geom name="pad_{b["name"]}" type="box" pos="{f((xlo + xhi) / 2)} {f((ylo + yhi) / 2)} 0.002" '
            f'size="{f((xhi - xlo) / 2)} {f((yhi - ylo) / 2)} 0.002" rgba="0.62 0.62 0.60 1" '
            f'contype="0" conaffinity="0"/>')
        r, g, bl = b["color"]
        add(f'    <geom name="{b["name"]}" type="box" pos="{f(b["cx"])} {f(b["cy"])} {f(b["h"] / 2)}" '
            f'size="{f(b["hx"])} {f(b["hy"])} {f(b["h"] / 2)}" rgba="{r:.2f} {g:.2f} {bl:.2f} 1"/>')

    # ---- destination marker (mocap so Python can move it to any intersection) ----
    add('    <!-- Destination: a visual-only site on a mocap body, moved at startup -->')
    add('    <body name="goal" mocap="true" pos="1.2 1.2 0.003">')
    add('      <site name="goal_marker" type="cylinder" size="0.12 0.003" rgba="1.0 0.25 0.10 0.9"/>')
    add('    </body>')

    # ---- obstacles (mocap, moved at startup) ----
    add(f'    <!-- obs_1..obs_{MAX_BARRIERS}: "road closed" barriers, as wide as the road (0.42 m), 20 cm tall. -->')
    add(f'    <!-- obs_{MAX_BARRIERS + 1}..obs_{MAX_BARRIERS + MAX_PARKED}: parked cars beside the lane. -->')
    add('    <!-- Unused obstacles are parked outside the city walls by run_city_sim.py. -->')
    for n in range(1, MAX_BARRIERS + 1):
        add(f'    <body name="obs_{n}" mocap="true" pos="{10 + n} 10 0.1">')
        add(f'      <geom name="obs_{n}_geom" type="box" size="0.03 0.21 0.10" rgba="1.0 0.55 0.05 1"/>')
        add('    </body>')
    for n in range(MAX_BARRIERS + 1, MAX_BARRIERS + MAX_PARKED + 1):
        add(f'    <body name="obs_{n}" mocap="true" pos="{10 + n} 10 0.05">')
        add(f'      <geom name="obs_{n}_geom" type="box" size="0.09 0.04 0.05" rgba="0.75 0.12 0.12 1"/>')
        add('    </body>')

    # ---- the car (same hardware as the open-arena version) ----
    add('''
    <!-- ===== The car: 150 x 100 mm plate, ESP32, battery, marker plate, 2 wheels, caster ===== -->
    <body name="car" pos="-1.2 -1.2 0.0305">
      <freejoint name="car_free"/>
      <geom name="chassis" type="box" size="0.075 0.050 0.002" pos="0 0 0" mass="0.060" rgba="0.15 0.15 0.18 1"/>
      <geom name="esp32" type="box" size="0.0225 0.014 0.003" pos="-0.025 0 0.005" mass="0.015" rgba="0.10 0.55 0.25 1"/>
      <!-- Battery just behind the axle (axle at +25 mm, battery at +10 mm) -->
      <geom name="battery" type="box" size="0.012 0.0225 0.009" pos="0.010 0 0.011" mass="0.075" rgba="0.85 0.65 0.10 1"/>
      <!-- Marker plate for the overhead camera; orange tag shows the front -->
      <geom name="marker_post" type="cylinder" size="0.004 0.0025" pos="0.010 0 0.0225" mass="0.002" contype="0" conaffinity="0" rgba="0.3 0.3 0.3 1"/>
      <geom name="marker_plate" type="box" size="0.03 0.03 0.0005" pos="0 0 0.025" mass="0.005" contype="0" conaffinity="0" rgba="1 1 1 1"/>
      <geom name="marker_pattern" type="box" size="0.02 0.02 0.0003" pos="0 0 0.0258" mass="0.0005" contype="0" conaffinity="0" rgba="0 0 0 1"/>
      <geom name="marker_front_tag" type="box" size="0.006 0.006 0.0003" pos="0.022 0 0.0258" mass="0.0001" contype="0" conaffinity="0" rgba="1.0 0.5 0.0 1"/>
      <!-- Low-friction rear caster, bottom flush with the wheels -->
      <geom name="caster" type="sphere" size="0.015" pos="-0.055 0 -0.015" mass="0.005" condim="1" friction="0.01 0.001 0.0001" rgba="0.7 0.7 0.7 1"/>
      <!-- Ultrasonic sensor: local +Z points forward with a 4 degree upward tilt -->
      <site name="sensor_site" type="sphere" size="0.005" pos="0.078 0 0.012" euler="0 86 0" rgba="1 0 0 1"/>
      <!-- Optional onboard camera: pick "car_cam" in the viewer to see the driver's view -->
      <camera name="car_cam" pos="0.06 0 0.04" xyaxes="0 -1 0 0 0 1" fovy="70"/>
      <body name="left_wheel" pos="0.025 0.054 0" euler="-90 0 0">
        <joint name="left_wheel_joint" type="hinge" axis="0 0 1" damping="0.0005"/>
        <geom name="left_wheel_geom" type="cylinder" size="0.03 0.004" mass="0.020" friction="1.2 0.005 0.0001" rgba="0.05 0.05 0.05 1"/>
      </body>
      <body name="right_wheel" pos="0.025 -0.054 0" euler="-90 0 0">
        <joint name="right_wheel_joint" type="hinge" axis="0 0 1" damping="0.0005"/>
        <geom name="right_wheel_geom" type="cylinder" size="0.03 0.004" mass="0.020" friction="1.2 0.005 0.0001" rgba="0.05 0.05 0.05 1"/>
      </body>
    </body>
  </worldbody>

  <!-- Continuous servos as wheel-speed controllers (ctrl in rad/s) -->
  <actuator>
    <velocity name="left_vel_servo"  joint="left_wheel_joint"  kv="0.02" ctrlrange="-10 10" forcerange="-0.05 0.05"/>
    <velocity name="right_vel_servo" joint="right_wheel_joint" kv="0.02" ctrlrange="-10 10" forcerange="-0.05 0.05"/>
  </actuator>

  <sensor>
    <rangefinder name="front_range" site="sensor_site" cutoff="4.0"/>
  </sensor>
</mujoco>
''')
    return "\n".join(x)


def write_city_xml(path=OUTPUT_PATH):
    with open(path, "w") as fh:
        fh.write(city_xml())
    return path


if __name__ == "__main__":
    print("wrote", write_city_xml(), f"({len(building_footprints())} buildings)")
